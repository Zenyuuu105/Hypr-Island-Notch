#!/usr/bin/env python3
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path.home() / ".config/quickshell/dotarch"
HYPR = Path.home() / ".config/hypr"
STATE = ROOT / "state/input.json"
MODULE = HYPR / "modules/desktop-input.lua"
CONFIG = HYPR / "hyprland.lua"

LAYOUTS = ["us", "gb", "ara", "de", "fr", "ru"]

DEFAULTS = {
    "sensitivity": 0.0,
    "kb_layout": "us",
    "natural_scroll": True,
    "tap_to_click": True,
    "disable_while_typing": True,
    "scroll_factor": 1.0,
}


def run(args):
    p = subprocess.run(args, text=True, capture_output=True)
    if p.returncode:
        raise RuntimeError(p.stderr.strip() or p.stdout.strip() or "Command failed")
    return p.stdout.strip()


def option(name):
    data = json.loads(run(["hyprctl", "getoption", name, "-j"]))
    if "bool" in data:
        return data["bool"]
    if "float" in data:
        return data["float"]
    if "int" in data:
        return data["int"]
    if "str" in data:
        return data["str"]
    return None


def live_settings():
    return {
        "sensitivity": float(option("input:sensitivity")),
        "kb_layout": option("input:kb_layout") or "us",
        "natural_scroll": bool(option("input:touchpad:natural_scroll")),
        "tap_to_click": bool(option("input:touchpad:tap-to-click")),
        "disable_while_typing": bool(option("input:touchpad:disable_while_typing")),
        "scroll_factor": float(option("input:touchpad:scroll_factor")),
    }


def lua_string(value):
    return json.dumps(value)


def render_module(settings):
    return f'''-- Generated by Dotarch Desktop Settings.
-- Manual edits may be overwritten.

hl.config({{
    input = {{
        kb_layout = {lua_string(settings["kb_layout"])},
        sensitivity = {settings["sensitivity"]:.4f},
        touchpad = {{
            natural_scroll = {str(settings["natural_scroll"]).lower()},
            ["tap-to-click"] = {str(settings["tap_to_click"]).lower()},
            disable_while_typing = {str(settings["disable_while_typing"]).lower()},
            scroll_factor = {settings["scroll_factor"]:.4f},
        }},
    }},
}})
'''


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(content)
        os.replace(temp, path)
    except Exception:
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise


def ensure_loader():
    text = CONFIG.read_text()
    line = 'require("modules.desktop-input")'
    if line in text:
        return
    anchor = 'require("modules.input")'
    if anchor not in text:
        raise RuntimeError("Could not find modules.input in hyprland.lua")
    atomic_write(CONFIG, text.replace(anchor, anchor + "\n" + line, 1))


def apply(settings):
    if settings["kb_layout"] not in LAYOUTS:
        raise ValueError("Unsupported keyboard layout")

    if not -1.0 <= float(settings["sensitivity"]) <= 1.0:
        raise ValueError("Pointer sensitivity must be between -1 and 1")

    if not 0.1 <= float(settings["scroll_factor"]) <= 10.0:
        raise ValueError("Scroll factor must be between 0.1 and 10")

    settings["sensitivity"] = float(settings["sensitivity"])
    settings["scroll_factor"] = float(settings["scroll_factor"])

    lua = render_module(settings).split("-- Manual edits may be overwritten.\n\n", 1)[1]
    run(["hyprctl", "eval", lua])

    # Verify the changed values before saving.
    actual = live_settings()
    for key in settings:
        expected = settings[key]
        received = actual[key]
        if isinstance(expected, float):
            if abs(float(expected) - float(received)) > 0.002:
                raise RuntimeError(f"Hyprland did not apply {key}")
        elif expected != received:
            raise RuntimeError(f"Hyprland did not apply {key}")

    atomic_write(STATE, json.dumps(settings, indent=2) + "\n")
    atomic_write(MODULE, render_module(settings))
    ensure_loader()


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "get":
        print(json.dumps(live_settings()))
        return

    if len(sys.argv) == 4 and sys.argv[1] == "set":
        settings = live_settings()
        key, value = sys.argv[2], sys.argv[3]

        if key not in DEFAULTS:
            raise ValueError("Unknown input setting")

        if key in ("natural_scroll", "tap_to_click", "disable_while_typing"):
            if value.lower() not in ("true", "false"):
                raise ValueError("Expected true or false")
            settings[key] = value.lower() == "true"
        elif key == "kb_layout":
            settings[key] = value
        else:
            settings[key] = float(value)

        apply(settings)
        print("Input setting applied and saved.")
        return

    raise RuntimeError("Usage: input-settings.py get | set KEY VALUE")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
