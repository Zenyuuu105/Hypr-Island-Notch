#!/usr/bin/env python3
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path.home() / ".config/quickshell/dotarch"
HYPR = Path.home() / ".config/hypr"
STATE_DIR = ROOT / "state"
STATE_FILE = STATE_DIR / "displays.json"
MODULE = HYPR / "modules/desktop-displays.lua"
CONFIG = HYPR / "hyprland.lua"

def run(args, check=True):
    p = subprocess.run(args, text=True, capture_output=True)
    if check and p.returncode != 0:
        raise RuntimeError(p.stderr.strip() or p.stdout.strip() or "Command failed")
    return p

def read_state():
    try:
        data = json.loads(STATE_FILE.read_text())
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}

def monitor_data():
    raw = run(["hyprctl", "monitors", "-j"]).stdout
    monitors = json.loads(raw)
    saved = read_state()
    result = []

    for m in monitors:
        name = m.get("name", "")
        width = int(m.get("width", 0))
        height = int(m.get("height", 0))
        refresh = float(m.get("refreshRate", 60))
        current_mode = f"{width}x{height}@{refresh:.2f}Hz"
        modes = m.get("availableModes", [])
        if current_mode not in modes and modes:
            # Prefer the available mode matching the current dimensions.
            matching = [x for x in modes if x.startswith(f"{width}x{height}@")]
            current_mode = matching[0] if matching else modes[0]

        configured = saved.get(name, {})
        result.append({
            "name": name,
            "description": m.get("description") or name,
            "make": m.get("make", ""),
            "model": m.get("model", ""),
            "width": width,
            "height": height,
            "refreshRate": refresh,
            "scale": float(configured.get("scale", m.get("scale", 1))),
            "mode": configured.get("mode", current_mode),
            "currentMode": current_mode,
            "availableModes": modes,
            "x": int(m.get("x", 0)),
            "y": int(m.get("y", 0)),
            "focused": bool(m.get("focused", False)),
            "disabled": bool(m.get("disabled", False)),
        })
    return result

def lua_string(value):
    return json.dumps(str(value), ensure_ascii=False)

def render_module(state):
    lines = [
        "-- Generated by Dotarch Desktop Settings.",
        "-- Manual edits may be overwritten.",
        ""
    ]
    for name, item in state.items():
        lines.append("hl.monitor({")
        lines.append(f"    output = {lua_string(name)},")
        lines.append(f"    mode = {lua_string(item['mode'])},")
        lines.append('    position = "auto",')
        lines.append(f"    scale = {float(item['scale']):.2f},")
        lines.append("})")
        lines.append("")
    return "\n".join(lines)

def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(content)
        os.replace(temp, path)
    except Exception:
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise

def ensure_loader():
    text = CONFIG.read_text()
    line = 'require("modules.desktop-displays")'
    if line in text:
        return
    anchor = 'require("modules.moniters")'
    if anchor not in text:
        raise RuntimeError("Could not find the existing monitor module in hyprland.lua")
    text = text.replace(anchor, anchor + "\n" + line, 1)
    atomic_write(CONFIG, text)

def apply(name, mode, scale):
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", name):
        raise ValueError("Invalid monitor name")
    if not re.fullmatch(r"\d{2,5}x\d{2,5}@\d+(?:\.\d+)?Hz", mode):
        raise ValueError("Invalid monitor mode")
    scale = float(scale)
    if not 0.5 <= scale <= 3.0:
        raise ValueError("Scale must be between 0.50 and 3.00")

    monitors = monitor_data()
    selected = next((m for m in monitors if m["name"] == name), None)
    if selected is None:
        raise RuntimeError(f"{name} is no longer connected")
    if mode not in selected["availableModes"]:
        raise RuntimeError(f"{mode} is not supported by {name}")

    lua = (
        "hl.monitor({"
        f"output={lua_string(name)},"
        f"mode={lua_string(mode)},"
        'position="auto",'
        f"scale={scale:.2f}"
        "})"
    )
    result = run(["hyprctl", "eval", lua])
    if result.stdout.strip() != "ok":
        raise RuntimeError(result.stdout.strip() or "Hyprland did not confirm the change")

    state = read_state()
    state[name] = {"mode": mode, "scale": scale}
    atomic_write(STATE_FILE, json.dumps(state, indent=2) + "\n")
    atomic_write(MODULE, render_module(state))
    ensure_loader()
    print("Display settings applied and saved.")

def main():
    if len(sys.argv) == 2 and sys.argv[1] == "get":
        print(json.dumps(monitor_data()))
        return
    if len(sys.argv) == 5 and sys.argv[1] == "apply":
        apply(sys.argv[2], sys.argv[3], sys.argv[4])
        return
    raise RuntimeError("Usage: display-settings.py get | apply MONITOR MODE SCALE")

if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(str(e), file=sys.stderr)
        sys.exit(1)
